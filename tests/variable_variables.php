<?php
// $name внутри строки и переменные-переменные ($$name).

$name = 'age';
$age = 30;

// Вне строки: $$name - переменная-переменная (DOLLAR + VARIABLE)
$$name = 42;
echo $$name;
$$$name = 'triple';           // переменная-переменная-переменная - тоже допустимо

// Внутри двойных кавычек ПРОСТОЙ синтаксис НЕ делает переменную-переменную:
// $$name трактуется как литеральный "$" + интерполированная $name.
echo "$$name";                // ожидаем: литерал "$" + Interpolated variable: $name
echo "$$$name";                // ожидаем: литерал "$$" (два раза по одному "$") + Interpolated variable: $name

// Чтобы получить настоящую переменную-переменную ВНУТРИ строки, нужен
// синтаксис {$...}:
echo "{$$name}";               // Dollar + Variable внутри InterpolationStart/End
echo "value is {$$$name} here";

// синтаксис ${name} - тоже просто $name,
// а НЕ переменная-переменная (несмотря на визуальное сходство с ${$name}):
echo "${name}";

echo "${$name}";

// Переменная-переменная как индекс/значение в массиве
$arr = [$$name => 'value'];
