<?php

$x = "42";

$a = (int)$x;
$b = (integer) $x;
$c = (float)$x;
$d = (double)$x;
$e = (real)$x;
$f = (string)$x;
$g = (binary)$x;
$h = (bool)$x;
$i = (boolean)$x;
$j = (array)$x;
$k = (object)$x;
$l = (unset)$x;

// Регистр не важен - каст-ключевые слова регистронезависимы, как и обычные
$m = (INT)$x;
$n = (Bool)$x;

// Пробелы внутри скобок допустимы в любом количестве
$o = ( int )$x;
$p = (   float   )$x;
$r = ( InT )$x;

// А вот это уже НЕ каст, а обычные скобки + идентификатор:
// внутри скобок имя класса, не входящее в список каст-ключевых слов
$q = (MyClass)$x;
$r = (SomeInterface)$x;

// Обычное выражение в скобках рядом с числом - тоже не каст
$s = (1 + 2) * $x;

$x = (int) + 1;         // это каст, ок
$x = (int);             // а вот это — не каст в PHP, это ошибка;
                        // лексер вправе выдать cast
$a = (int) (float)$x;   // два каста подряд

// НЕ касты:
$b = (integerValue);    // идентификатор, не каст
$c = (int;              // незакрытая скобка
$d = (int $x;           // внутри скобок пробел и переменная — не каст
$e = (int)value;        // каст без пробела —  каст
$f = (int)($x);         // каст + скобки — каст

// комментарий внутри уже НЕ каста
$z = ( /* comment */ int )$x;

// многострочный НЕ каст
$z = (
    // comment
    int
)$x;

// Перевод строки перед ключевым словом - НЕ каст
$x = (
   int
)$y;

// Каст с табом
$x = (  int	)$y;

// Каст в середине выражения
$x = 1 + (int)$y + 2;

// Двойные скобки вокруг каста
$x = ((int)$y);

// Каст внутри аргумента функции
f((int)$y, (string)$z);